"""Generates the Woodshed logo: assets/logo.svg and the Android launcher icon layers.

One shape list feeds both outputs, so the SVG and the app icon cannot drift apart.
Run from the repo root: python3 tools/logo.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"

BODY = ("#f7aed0", "#d8639c")  # matte pink, lighter at the top, as in Callie's logo
LOG = ("#fff1e4", "#f8cfae")
ROOF, OPENING, SLAT, RING, INK, BLUSH = "#a23f72", "#7c2d58", "#c24d86", "#e7a77f", "#3a1630", "#f29bb9"
BACKGROUND = "#fbf0f5"

WALLS = "M20 46 Q20 34 32 35 L98 41 Q110 42 110 54 L110 98 Q110 116 92 116 L36 116 Q20 116 20 98 Z"
ROOF_PLANK = "M12 30 Q10 22 20 22 L112 31 Q121 32 120 40 Q119 46 112 45 L18 37 Q12 36 12 30 Z"
DOORWAY = "M34 54 Q34 46 42 47 L88 51 Q96 52 96 60 L96 96 Q96 104 88 104 L42 104 Q34 104 34 96 Z"
SLATS = ["M25 62 H29", "M25 76 H29", "M25 90 H29", "M101 66 H105", "M101 80 H105", "M101 94 H105"]
LOGS = [(47, 92, 9.5), (65, 92, 9.5), (83, 92, 9.5), (56, 75, 9.5), (74, 75, 9.5), (65, 59, 8)]
RINGS = [(47, 92, 4), (83, 92, 4), (56, 75, 4), (74, 75, 4), (65, 59, 3.2)]
CHEEKS = [(59.5, 95), (70.5, 95)]
FACE = ["M59 91 Q61 88.5 63 91", "M67 91 Q69 88.5 71 91", "M63 95 Q65 97 67 95"]


def circle(cx, cy, r):
    return f"M{cx - r} {cy} A{r} {r} 0 1 0 {cx + r} {cy} A{r} {r} 0 1 0 {cx - r} {cy} Z"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx} {cy} A{rx} {ry} 0 1 0 {cx + rx} {cy} A{rx} {ry} 0 1 0 {cx - rx} {cy} Z"


def svg():
    def grad(id_, stops, x2="0.3"):
        return (f'<linearGradient id="{id_}" x1="0" y1="0" x2="{x2}" y2="1">'
                f'<stop offset="0" stop-color="{stops[0]}"/><stop offset="1" stop-color="{stops[1]}"/></linearGradient>')
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="128" height="128" role="img" aria-labelledby="t">',
        '  <title id="t">Woodshed</title>',
        f'  <defs>{grad("body", BODY)}{grad("log", LOG, "0")}</defs>',
        "  <!-- a lean-to woodshed: the left wall stands taller, so the roof slopes to the right -->",
        f'  <path d="{WALLS}" fill="url(#body)"/>',
        f'  <path d="{ROOF_PLANK}" fill="{ROOF}"/>',
        f'  <path d="{DOORWAY}" fill="{OPENING}"/>',
        f'  <g stroke="{SLAT}" stroke-width="3" stroke-linecap="round" opacity="0.55">'
        + "".join(f'<path d="{d}"/>' for d in SLATS) + "</g>",
        "  <!-- stacked log ends, and a happy face on the middle one -->",
        f'  <g fill="url(#log)" stroke="{RING}" stroke-width="2.5">'
        + "".join(f'<circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in LOGS) + "</g>",
        f'  <g fill="none" stroke="{RING}" stroke-width="2" opacity="0.7">'
        + "".join(f'<circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in RINGS) + "</g>",
        f'  <g fill="{BLUSH}" opacity="0.85">' + "".join(f'<ellipse cx="{x}" cy="{y}" rx="2.6" ry="1.6"/>' for x, y in CHEEKS) + "</g>",
        f'  <g fill="none" stroke="{INK}" stroke-linecap="round" stroke-width="2">' + "".join(f'<path d="{d}"/>' for d in FACE) + "</g>",
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


# The 128-unit logo sits in the middle 72 of the icon's 108, inside the adaptive-icon safe zone.
GROUP = '<group android:translateX="18" android:translateY="18" android:scaleX="0.5625" android:scaleY="0.5625">'
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/logo.py; edit that instead. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def vd_path(d, fill=None, gradient=None, stroke=None, width=None, alpha=None, extra=""):
    attrs = [f'android:pathData="{d}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{width}"', 'android:strokeLineCap="round"']
    if alpha is not None:
        attrs.append(f'android:{"strokeAlpha" if stroke and not fill else "fillAlpha"}="{alpha}"')
    attrs.append(extra)
    body = ""
    if gradient:
        (top, bottom), (x1, y1, x2, y2) = gradient
        body = (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
                f'android:endX="{x2}" android:endY="{y2}" android:startColor="{top}" android:endColor="{bottom}"/></aapt:attr>')
    return f'  <path {" ".join(a for a in attrs if a)}>{body}</path>\n'


def foreground(head=None, group=None):
    out = (head or HEAD) + (group or GROUP) + "\n"
    out += vd_path(WALLS, gradient=(BODY, (20, 34, 47, 116)))
    out += vd_path(ROOF_PLANK, fill=ROOF)
    out += vd_path(DOORWAY, fill=OPENING)
    out += "".join(vd_path(d, stroke=SLAT, width=3, alpha=0.55) for d in SLATS)
    for x, y, r in LOGS:
        out += vd_path(circle(x, y, r), gradient=(LOG, (x, y - r, x, y + r)), extra=f'android:strokeColor="{RING}" android:strokeWidth="2.5"')
    out += "".join(vd_path(circle(x, y, r), stroke=RING, width=2, alpha=0.7) for x, y, r in RINGS)
    out += "".join(vd_path(ellipse(x, y, 2.6, 1.6), fill=BLUSH, alpha=0.85) for x, y in CHEEKS)
    out += "".join(vd_path(d, stroke=INK, width=2) for d in FACE)
    return out + "</group>\n</vector>\n"


def monochrome():
    """Themed icons tint one silhouette: the shed with its doorway cut out, and the logs inside."""
    out = HEAD + GROUP + "\n"
    out += vd_path(WALLS + " " + DOORWAY, fill="#000000", extra='android:fillType="evenOdd"')
    out += vd_path(ROOF_PLANK, fill="#000000")
    out += "".join(vd_path(circle(x, y, r - 1.5), fill="#000000") for x, y, r in LOGS)
    return out + "</group>\n</vector>\n"


# The logo alone at its own 128-unit size, for showing inside the app.
LOGO_HEAD = HEAD.replace('android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108"',
                         'android:width="128dp" android:height="128dp" android:viewportWidth="128" android:viewportHeight="128"')


def background():
    return (HEAD + f'  <path android:pathData="M0,0h108v108h-108z" android:fillColor="{BACKGROUND}"/>\n</vector>\n')


if __name__ == "__main__":
    (ROOT / "assets").mkdir(exist_ok=True)
    (ROOT / "assets/logo.svg").write_text(svg())
    (RES / "ic_launcher_foreground.xml").write_text(foreground())
    (RES / "ic_launcher_monochrome.xml").write_text(monochrome())
    (RES / "ic_launcher_background.xml").write_text(background())
    (RES / "logo.xml").write_text(foreground(LOGO_HEAD, "<group>"))
    print("wrote assets/logo.svg, the launcher icon layers and the in-app logo")
